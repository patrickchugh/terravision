#!/usr/bin/env python3
"""Generate the icon classes in resource_classes/<cloud>/icons.py.

    poetry run python scripts/generate_icon_classes.py           # write them
    poetry run python scripts/generate_icon_classes.py --check   # exit 1 if stale

Each icon file resource_images/<cloud>/<folder>/<name>.png gets one class,
named from the file: network/direct-connect-gateway.png becomes
DirectConnectGateway. A name that two folders share gets its folder in front
(AnalyticsRedshift, DatabaseRedshift), and so does one that would shadow a
class in groups.py: drawing.py loads every module of a cloud into one
namespace, so two classes with one name would silently replace each other.

Which Terraform types draw with which icon is not generated: it is the
hand-maintained resource_classes/<cloud>/terraform_icons.yml, applied by the
last line of each icons.py. Run this after adding, renaming or removing icon
files; it fails if terraform_icons.yml names an icon that no longer exists.
"""

import argparse
import importlib
import re
import sys
from pathlib import Path

import black
import yaml

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

# Cloud -> (base class in resource_classes/<cloud>/__init__.py, display name)
CLOUDS = {"aws": ("_AWS", "AWS"), "azure": ("_Azure", "Azure"), "gcp": ("_GCP", "GCP")}

HEADER = '''"""{display} icon classes: one per icon in resource_images/{cloud}/.

Generated by scripts/generate_icon_classes.py from the icon files; do not
edit. The Terraform types each icon draws are set in terraform_icons.yml and
become module-level names (``aws_dx_gateway = DirectConnectGateway``) through
the last line of this file.
"""

from resource_classes import add_terraform_types

from . import {base}
'''

CLASS = """

class {name}({base}):
    _type = "{type}"
    _icon_dir = "{icon_dir}"
    _icon = "{file}"
"""

FOOTER = """

add_terraform_types(globals(), "{cloud}")
"""


def camel(text: str) -> str:
    """direct-connect-gateway -> DirectConnectGateway."""
    name = "".join(p[:1].upper() + p[1:] for p in re.split(r"[^A-Za-z0-9]+", text))
    return f"Icon{name}" if name[:1].isdigit() else name


def mapping(cloud: str) -> dict:
    """terraform_icons.yml: Terraform type -> icon key."""
    path = ROOT / "resource_classes" / cloud / "terraform_icons.yml"
    return (yaml.safe_load(path.read_text()) or {}) if path.exists() else {}


def icons(cloud: str) -> dict:
    """Icon key -> (icon_dir, file), the keys terraform_icons.yml uses.

    Every icon in a folder of resource_images/<cloud>/ (``network/vpc``), and
    the shared icons the mapping borrows from elsewhere in resource_images/
    (``generic/compute/rack``) for pseudo-nodes such as tv_azurerm_server.
    """
    found = {}
    base = ROOT / "resource_images" / cloud
    for path in sorted(base.glob("*/*.png")):
        found[f"{path.parent.name}/{path.stem}"] = (
            f"resource_images/{cloud}/{path.parent.name}",
            path.name,
        )
    for key in sorted(set(mapping(cloud).values())):
        folder, _, stem = key.rpartition("/")
        if (
            key.count("/") > 1
            and (ROOT / "resource_images" / folder / f"{stem}.png").exists()
        ):
            found[key] = (f"resource_images/{folder}", f"{stem}.png")
    return found


def reserved(cloud: str) -> set:
    """Public names groups.py and the package itself already define."""
    names = set()
    for module in (f"resource_classes.{cloud}", f"resource_classes.{cloud}.groups"):
        names.update(n for n in dir(importlib.import_module(module)) if n[:1] != "_")
    return names


def class_names(cloud: str, keys) -> dict:
    """Icon key -> class name, unique within the cloud."""
    taken = reserved(cloud)
    plain = {}
    for key in keys:
        plain.setdefault(camel(key.rpartition("/")[2]), []).append(key)
    names = {}
    for name, owners in plain.items():
        for key in owners:
            prefixed = len(owners) > 1 or name in taken
            names[key] = camel(key.rpartition("/")[0]) + name if prefixed else name
    # Files in one folder that differ only in punctuation (aws network/
    # private-subnet and private_subnet, the subnet box badge) keep the
    # underscore apart.
    counts = {}
    for name in names.values():
        counts[name] = counts.get(name, 0) + 1
    for key, name in names.items():
        if counts[name] > 1 and "_" in key.rpartition("/")[2]:
            folder, _, stem = key.rpartition("/")
            names[key] = camel(folder) + "_".join(camel(p) for p in stem.split("_"))
    seen = {}
    for key, name in names.items():
        if name in seen or name in taken:
            sys.exit(
                f"{cloud}: {key} and {seen.get(name, 'groups.py')} both make {name}"
            )
        seen[name] = key
    return names


def check_mapping(cloud: str, have) -> None:
    """Fail if terraform_icons.yml names a missing icon or a container type."""
    containers = reserved(cloud)
    problems = []
    for resource_type, key in mapping(cloud).items():
        if key not in have:
            problems.append(f"{resource_type}: no icon {key}")
        if resource_type in containers:
            problems.append(f"{resource_type}: drawn as a container by groups.py")
    if problems:
        sys.exit(
            f"resource_classes/{cloud}/terraform_icons.yml:\n  " + "\n  ".join(problems)
        )


def render(cloud: str) -> str:
    base, display = CLOUDS[cloud]
    found = icons(cloud)
    check_mapping(cloud, found)
    names = class_names(cloud, found)
    parts = [HEADER.format(display=display, cloud=cloud, base=base)]
    for key, (icon_dir, file) in found.items():
        parts.append(
            CLASS.format(
                name=names[key],
                base=base,
                type=Path(icon_dir).name,
                icon_dir=icon_dir,
                file=file,
            )
        )
    parts.append(FOOTER.format(cloud=cloud))
    # Black-formatted, so the pre-commit hook leaves the file as written
    return black.format_str("".join(parts), mode=black.Mode())


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument(
        "--check", action="store_true", help="exit 1 if any icons.py is out of date"
    )
    args = parser.parse_args()
    stale = []
    for cloud in CLOUDS:
        target = ROOT / "resource_classes" / cloud / "icons.py"
        text = render(cloud)
        if target.exists() and target.read_text() == text:
            continue
        if args.check:
            stale.append(str(target.relative_to(ROOT)))
        else:
            target.write_text(text)
            print(f"wrote {target.relative_to(ROOT)}")
    if stale:
        sys.exit(
            "out of date, run scripts/generate_icon_classes.py: " + ", ".join(stale)
        )


if __name__ == "__main__":
    main()
